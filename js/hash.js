// FNV-1a. Used to turn a fingerprint's rounded feature string into a stable
// integer seed, so the same sound always yields the same design.
export function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
