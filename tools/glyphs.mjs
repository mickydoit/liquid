export const GLYPH_W = 5;
export const GLYPH_H = 7;

// Draw `text` into an RGB buffer at (x0, y0), `scale` pixels per font pixel.
export function drawText(rgb, imgW, imgH, text, x0, y0, scale, colour) {
  let cx = x0;
  for (const ch of text.toUpperCase()) {
    const g = G[ch];
    if (g) {
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          if (g[r][c] !== '1') continue;
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + c * scale + sx, py = y0 + r * scale + sy;
              if (px < 0 || py < 0 || px >= imgW || py >= imgH) continue;
              const o = (py * imgW + px) * 3;
              rgb[o] = colour[0]; rgb[o + 1] = colour[1]; rgb[o + 2] = colour[2];
            }
          }
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
